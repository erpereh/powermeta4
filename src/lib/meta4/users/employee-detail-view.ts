const SECTION_TITLES: Record<string, string> = {
  identity: "Datos personales",
  role: "Puesto y organización",
  workplace: "Centro de trabajo",
  labor: "Datos laborales",
  other: "Otros datos",
};

const SECTION_ORDER = ["identity", "role", "workplace", "labor", "other"];

export const pickField = (fields: Record<string, string>, name: string): string => {
  const found = Object.entries(fields).find(([key]) => key.toLowerCase() === name.toLowerCase());
  return found?.[1] ?? "";
};

export const buildEmployeeSections = (
  fields: Record<string, string>,
): Meta4ProfileSectionView[] => {
  const buckets = new Map<string, Meta4ProfileFieldView[]>();
  const push = (section: string, field: Meta4ProfileFieldView) => {
    const list = buckets.get(section) ?? [];
    list.push(field);
    buckets.set(section, list);
  };

  for (const [key, raw] of Object.entries(fields)) {
    if (EXCLUDED_FIELD_KEYS.has(key.toLowerCase())) continue;
    const known = KNOWN_FIELD_LABELS[key];
    push(known?.section ?? "other", {
      key,
      label: known?.label ?? humanizeKey(key),
      value: formatFieldValue(raw),
    });
  }

  return SECTION_ORDER.filter((id) => (buckets.get(id)?.length ?? 0) > 0).map((id) => ({
    id,
    title: SECTION_TITLES[id] ?? id,
    fields: buckets.get(id) ?? [],
  }));
};

const formatEmailDateRange = (startDate: string, endDate: string): string => {
  const start = formatFieldValue(startDate);
  const end = endDate.trim() === OPEN_ENDED_DATE ? "Vigente" : formatFieldValue(endDate);
  return `${start} – ${end}`;
};

export const buildEmployeeEmails = (result: EmployeeDetailResult): Meta4EmployeeEmailView[] =>
  [...result.emails]
    .sort((a, b) => Number(a.order) - Number(b.order))
    .map((email) => ({
      email: email.email,
      dateRange: formatEmailDateRange(email.startDate, email.endDate),
    }));
