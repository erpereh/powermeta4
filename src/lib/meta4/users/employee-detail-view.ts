  id_Legal: { section: "identity", label: "DNI" },
  fec_Nacimiento: { section: "identity", label: "Fecha de nacimiento" },
  num_Afiliacion_Ss: { section: "identity", label: "Nº afiliación S.S." },
  clave_Self: { section: "identity", label: "Usuario Meta4" },
  id_Empleado: { section: "identity", label: "Id. empleado" },
  correo: { section: "identity", label: "Correo principal" },
  correo2: { section: "identity", label: "Correo secundario" },
  n_Puesto: { section: "role", label: "Puesto" },
  n_Clase_Puesto: { section: "role", label: "Clase de puesto" },
  n_Unidad: { section: "role", label: "Unidad" },
