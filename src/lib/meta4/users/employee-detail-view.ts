/** Sentinel end date Meta4 uses to mean "no end date / still active". */
const OPEN_ENDED_DATE = "4000-01-01T00:00:00.000Z";

/** Meta4 record-keeping noise, never shown regardless of section. */
const EXCLUDED_FIELD_KEYS = new Set(["m4autogeneratedrecordid", "m4autogeneratedtodelete"]);

