export const HOLIDAY_SQL = {
  roles: `SELECT DISTINCT SCO_OR_HR_ROLE AS ROLE_ID
FROM M4SCO_HR_ROLE
WHERE ID_ORGANIZATION = @organization AND SCO_ID_HR = @employeeId
  AND SCO_MAIN_ROLE = '1' AND SCO_DT_END >= @today`,

  calendar: `WITH locations AS (
SELECT ROW_NUMBER() OVER (ORDER BY H.SCO_DT_START, H.SCO_DT_END, H.SCO_ID_WORK_LOC) AS LOCATION_KEY,
  H.SCO_ID_WORK_LOC AS LOCATION_ID, W.STD_ID_WL_TYPE AS LOCATION_TYPE,
  CASE WHEN H.SCO_DT_START > @yearStart THEN H.SCO_DT_START ELSE @yearStart END AS DATE_FROM,
  CASE WHEN H.SCO_DT_END < @yearEnd THEN H.SCO_DT_END ELSE @yearEnd END AS DATE_TO
FROM M4SCO_H_HR_WLOC H
LEFT JOIN STD_WORK_LOCATION W ON W.ID_ORGANIZATION = @organization
  AND W.STD_ID_WORK_LOCAT = H.SCO_ID_WORK_LOC
WHERE H.ID_ORGANIZATION = @organization AND H.SCO_ID_HR = @employeeId
  AND H.SCO_OR_HR_ROLE = @roleId
  AND H.SCO_DT_START <= @yearEnd AND H.SCO_DT_END >= @yearStart
), paths AS (
SELECT LOCATION_KEY, CAST(LOCATION_ID AS varchar(255)) AS LOCATION_ID,
  CAST(LOCATION_TYPE AS varchar(16)) AS LOCATION_TYPE, DATE_FROM, DATE_TO,
  CAST('/' + LOCATION_ID + '/' AS varchar(max)) AS VISITED, 0 AS DEPTH
FROM locations
UNION ALL
SELECT P.LOCATION_KEY, CAST(R.STD_ID_WL_PARENT AS varchar(255)), CAST(W.STD_ID_WL_TYPE AS varchar(16)),
  CASE WHEN R.STD_DT_START > P.DATE_FROM THEN R.STD_DT_START ELSE P.DATE_FROM END,
  CASE WHEN R.STD_DT_END < P.DATE_TO THEN R.STD_DT_END ELSE P.DATE_TO END,
  CAST(P.VISITED + R.STD_ID_WL_PARENT + '/' AS varchar(max)), P.DEPTH + 1
FROM paths P
JOIN STD_REL_WORK_LOC R ON R.ID_ORGANIZATION = @organization
  AND R.STD_ID_WL_CHILD = P.LOCATION_ID
JOIN STD_WORK_LOCATION W ON W.ID_ORGANIZATION = @organization
  AND W.STD_ID_WORK_LOCAT = R.STD_ID_WL_PARENT
WHERE (P.LOCATION_TYPE IS NULL OR P.LOCATION_TYPE <> '1') AND P.DEPTH < 50
  AND R.STD_DT_START <= @hierarchyDate AND R.STD_DT_END >= @hierarchyDate
  AND R.STD_DT_START <= P.DATE_TO AND R.STD_DT_END >= P.DATE_FROM
  AND CHARINDEX('/' + R.STD_ID_WL_PARENT + '/', P.VISITED) = 0
), centers AS (
SELECT LOCATION_KEY, LOCATION_ID AS CENTER_ID, DATE_FROM, DATE_TO
FROM paths WHERE LOCATION_TYPE = '1'
), candidates AS (
SELECT 'role' AS SOURCE, NULLIF(LTRIM(RTRIM(V.SCO_VALUE)), '') AS CALENDAR_ID,
  CASE WHEN V.DT_START > @yearStart THEN V.DT_START ELSE @yearStart END AS DATE_FROM,
  CASE WHEN V.DT_END < @yearEnd THEN V.DT_END ELSE @yearEnd END AS DATE_TO,
  V.ID_PRIORITY
FROM M4SCO_ROLE_VALUES V
WHERE V.ID_ORGANIZATION = @organization AND V.SCO_ID_HR = @employeeId
  AND V.SCO_OR_HR_ROLE = @roleId AND V.ID_DMD = @dimension AND V.ID_DMD_COMPONENT = @component
  AND V.DT_COR_START <= @correctionDate AND V.DT_COR_END >= @correctionDate
  AND V.DT_START <= @yearEnd AND V.DT_END >= @yearStart
UNION ALL
SELECT 'center', NULLIF(LTRIM(RTRIM(V.SCO_VALUE)), ''),
  CASE WHEN V.DT_START > C.DATE_FROM THEN V.DT_START ELSE C.DATE_FROM END,
  CASE WHEN V.DT_END < C.DATE_TO THEN V.DT_END ELSE C.DATE_TO END, V.ID_PRIORITY
FROM centers C
JOIN M4SCO_WC_VALUES V ON V.ID_ORGANIZATION = @organization
  AND V.SCO_ID_WORK_CENTE = C.CENTER_ID
WHERE V.ID_DMD = @dimension AND V.ID_DMD_COMPONENT = @component
  AND V.DT_COR_START <= @correctionDate AND V.DT_COR_END >= @correctionDate
  AND V.DT_START <= C.DATE_TO AND V.DT_END >= C.DATE_FROM
UNION ALL
SELECT 'country', NULLIF(LTRIM(RTRIM(V.SCO_VALUE)), ''),
  B.DATE_FROM, B.DATE_TO, V.ID_PRIORITY
FROM centers C
JOIN M4SSP_WORKLOC_ADDR A ON A.ID_ORGANIZATION = @organization
  AND A.STD_ID_WORK_LOCAT = C.CENTER_ID
JOIN M4SCO_V_COUNTRY V ON V.ID_ORGANIZATION = @organization
  AND V.STD_ID_COUNTRY = A.STD_ID_NACION
CROSS APPLY (SELECT MAX(D) AS DATE_FROM FROM (VALUES (C.DATE_FROM), (A.SSP_FEC_INICIO), (V.DT_START)) X(D)) F
CROSS APPLY (SELECT MIN(D) AS DATE_TO FROM (VALUES (C.DATE_TO), (A.SSP_FEC_FIN), (V.DT_END)) X(D)) T
CROSS APPLY (SELECT F.DATE_FROM, T.DATE_TO) B
WHERE V.ID_DMD = @dimension AND V.ID_DMD_COMPONENT = @component
  AND V.DT_COR_START <= @correctionDate AND V.DT_COR_END >= @correctionDate
  AND A.SSP_FEC_INICIO <= C.DATE_TO AND A.SSP_FEC_FIN >= C.DATE_FROM
  AND V.DT_START <= C.DATE_TO AND V.DT_END >= C.DATE_FROM
  AND B.DATE_FROM <= B.DATE_TO
)
SELECT 'location' AS ROW_KIND, LOCATION_KEY, LOCATION_ID AS REFERENCE_ID,
  CAST(NULL AS varchar(16)) AS SOURCE, CAST(NULL AS varchar(255)) AS CALENDAR_ID,
  CONVERT(varchar(10), DATE_FROM, 23) AS DATE_FROM, CONVERT(varchar(10), DATE_TO, 23) AS DATE_TO,
  CAST(NULL AS varchar(10)) AS HOLIDAY_DATE, CAST(NULL AS varchar(max)) AS DESCRIPTION
FROM locations
UNION ALL
SELECT 'center', LOCATION_KEY, CENTER_ID, NULL, NULL,
  CONVERT(varchar(10), DATE_FROM, 23), CONVERT(varchar(10), DATE_TO, 23), NULL, NULL FROM centers
UNION ALL
SELECT 'assignment', NULL, NULL, SOURCE, CALENDAR_ID,
  CONVERT(varchar(10), DATE_FROM, 23), CONVERT(varchar(10), DATE_TO, 23), NULL, NULL FROM candidates
UNION ALL
SELECT 'holiday', NULL, NULL, NULL, C.CALENDAR_ID, NULL, NULL,
  CONVERT(varchar(10), D.SCO_DT_DAY, 23), D.SCO_COMMENT
FROM candidates C
JOIN M4SCO_CALENDAR_REP D ON D.ID_ORGANIZATION = @organization
  AND D.SCO_ID_CALENDAR = C.CALENDAR_ID
WHERE D.SCO_DT_DAY >= C.DATE_FROM AND D.SCO_DT_DAY <= C.DATE_TO
  AND D.SCO_DT_DAY >= @yearStart AND D.SCO_DT_DAY <= @yearEnd
OPTION (MAXRECURSION 50)`,
} as const;
