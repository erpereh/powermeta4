/** Reutiliza una lectura propia documentada, restringiéndola al equipo en SQL. */
export function ownQueryForTeam(query: PortalSqlQuery): PortalSqlQuery {
  const key = /\b([A-Z]+\.[A-Z0-9_]+) = @employeeId\b/.exec(query.statement)?.[1];
  if (query.scope !== "own" || !key || /\bGROUP BY\b/i.test(query.statement))
    throw new Error("La lectura no admite adaptación directa al equipo.");
  return {
    scope: "team",
    tables: query.tables,
    statement: query.statement
      .replace(/^SELECT /, `SELECT ${key} AS PORTAL_EMPLOYEE_ID, `)
      .replaceAll(`${key} = @employeeId`, `${key} IN (@team)`),
  };
}
