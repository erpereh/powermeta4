const level = (alias: string, column: string) =>
  `(SELECT TOP 1 L.STD_N_LANG_LEVESP FROM STD_LU_LANG_LEVEL L
    WHERE L.ID_ORGANIZATION = H.ID_ORGANIZATION AND L.STD_ID_LANG_LEVEL = H.${column}) AS ${alias}`;

