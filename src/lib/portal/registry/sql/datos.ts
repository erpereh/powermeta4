import type { PortalSqlQuery } from "../../types";

/**
 * Lecturas de «Mis datos» reproducidas desde las sentencias Meta4 originales
 * (`docs/portal/implementacion/lecturas-sql.md`). Los datos personales estándar
 * (`STD_*`) viven en la organización compartida `0000`; los de nómina, en la
 * sociedad. Los catálogos se leen en español (`…ESP`).
 */

const own = (tables: readonly string[], statement: string): PortalSqlQuery => ({
  scope: "own",
  tables,
  statement,
});

/** `SSE_ADDRESS!M4T_ADDRESS` / `SSE_ADDRESS_OTROS!M4T_ADDRESS_OTROS`: domicilios vigentes. */
const address = (locationFilter: string) =>
  own(
    [
      "STD_ADDRESS",
      "STD_COUNTRY",
      "STD_GEO_DIV",
      "STD_SUB_GEO_DIV",
      "STD_GEO_PLACE",
      "STD_LU_LOCAT_TYPE",
    ],
    `SELECT A.STD_ADDRESS_LINE_1 AS STD_ADDRESS_LINE_1, A.SSP_NUM_VIA AS SSP_NUM_VIA,
  A.SSP_BLOQUE AS SSP_BLOQUE, A.SSP_PISO AS SSP_PISO, A.SSP_ESCALERA AS SSP_ESCALERA,
  A.SSP_PUERTA AS SSP_PUERTA, COALESCE(A.SSP_DISTRIT_POSTAL, A.STD_ZIP_CODE) AS SSP_DISTRIT_POSTAL,
  P.STD_N_GEO_PLACESP AS STD_N_GEO_PLACE, S.STD_N_SUB_GEO_ESP AS STD_N_SUB_GEO_DIV,
  G.STD_N_GEO_DIVESP AS STD_N_GEO_DIV, C.STD_N_COUNTRYESP AS STD_N_COUNTRY,
  T.STD_N_LOCAT_TYESP AS STD_N_LOCATION_TYPE, A.STD_DT_START AS STD_DT_START
FROM STD_ADDRESS A
LEFT JOIN STD_COUNTRY C ON C.ID_ORGANIZATION = A.ID_ORGANIZATION AND C.STD_ID_COUNTRY = A.STD_ID_COUNTRY
LEFT JOIN STD_GEO_DIV G ON G.ID_ORGANIZATION = A.ID_ORGANIZATION AND G.STD_ID_COUNTRY = A.STD_ID_COUNTRY
  AND G.STD_ID_GEO_DIV = A.STD_ID_GEO_DIV
LEFT JOIN STD_SUB_GEO_DIV S ON S.ID_ORGANIZATION = A.ID_ORGANIZATION AND S.STD_ID_COUNTRY = A.STD_ID_COUNTRY
  AND S.STD_ID_GEO_DIV = A.STD_ID_GEO_DIV AND S.STD_ID_SUB_GEO_DIV = A.STD_ID_SUB_GEO_DIV
LEFT JOIN STD_GEO_PLACE P ON P.ID_ORGANIZATION = A.ID_ORGANIZATION AND P.STD_ID_COUNTRY = A.STD_ID_COUNTRY
  AND P.STD_ID_GEO_DIV = A.STD_ID_GEO_DIV AND P.STD_ID_SUB_GEO_DIV = A.STD_ID_SUB_GEO_DIV
  AND P.STD_ID_GEO_PLACE = A.STD_ID_GEO_PLACE
LEFT JOIN STD_LU_LOCAT_TYPE T ON T.ID_ORGANIZATION = A.ID_ORGANIZATION AND T.STD_ID_LOCAT_TYPE = A.STD_ID_LOCAT_TYPE
WHERE A.ID_ORGANIZATION IN ('0000', @organization) AND A.STD_ID_PERSON = @employeeId
  AND A.STD_DT_END >= @today AND ${locationFilter}
ORDER BY A.STD_DT_START DESC`,
  );

