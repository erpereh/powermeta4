/**
 * Fixed, server-only SELECT statements for C05 (telework) and C11 (previous excess).
 * Every identifier is constant; society, dates and frequency are bound parameters.
 */
const accumulatorJoin = `FROM M4SCO_AC_HR_PERIOD A
JOIN M4CSP_AC_HR_PERIOD B ON B.ID_ORGANIZATION = A.ID_ORGANIZATION
 AND B.SCO_ID_HR = A.SCO_ID_HR AND B.SCO_OR_HR_PERIOD = A.SCO_OR_HR_PERIOD
 AND B.SCO_DT_ALLOC = A.SCO_DT_ALLOC AND B.SCO_DT_PAYMENT = A.SCO_DT_PAYMENT
 AND B.SCO_DT_START_SLICE = A.SCO_DT_START_SLICE AND B.ID_CURRENCY = A.ID_CURRENCY
 AND B.SCO_PAY_FREQ_ALLOC = A.SCO_PAY_FREQ_ALLOC AND B.SCO_PAY_FREQ_PAY = A.SCO_PAY_FREQ_PAY
WHERE A.ID_ORGANIZATION = @organization AND A.SCO_DT_PAYMENT = @paymentDate
 AND A.SCO_DT_ALLOC = @paymentDate AND A.SCO_IND_MAIN_CURR = 1
 AND A.SCO_PAY_FREQ_PAY = @frequency AND A.SCO_PAY_FREQ_ALLOC = @frequency`;

const components = "('CSP_IND_ABONO_TELETRABAJO','CSP_P_ABONO_TELETRABAJO')";
const validValues = `ID_DMD = 'DMD1' AND ID_DMD_COMPONENT IN ${components}
 AND DT_START <= @lastDay AND DT_END >= @firstDay
 AND DT_COR_START <= @correctionDate AND DT_COR_END >= @correctionDate`;
/**
 * Also rows starting the day after the month: Meta4 keeps no prior version, so a
 * row rewritten after the calculation proves the configuration that paid is unknown.
 */
const candidateValues = `ID_DMD = 'DMD1' AND ID_DMD_COMPONENT IN ${components}
 AND DT_START <= @nextDay AND DT_END >= @firstDay
 AND DT_COR_START <= @correctionDate AND DT_COR_END >= @correctionDate`;
/** Real write time: the correction date can predate an in-place edit. */
const written = `CONVERT(varchar(19), CASE WHEN DT_LAST_UPDATE > DT_COR_START
  THEN DT_LAST_UPDATE ELSE DT_COR_START END, 120)`;

export const TELEWORK_SQL = {
  payroll: `SELECT A.SCO_ID_HR AS EMPLOYEE, A.SCO_OR_HR_PERIOD AS HR_PERIOD,
 A.STD_ID_LEG_ENT AS ENTITY,
 CONVERT(varchar(10), A.SCO_DT_START_SLICE, 23) AS DATE_FROM,
 CONVERT(varchar(10), A.SCO_DT_END_SLICE, 23) AS DATE_TO,
 CONVERT(varchar(30), A.SSP_ES_ALTA) AS NEW_HIRE,
 CONVERT(varchar(100), B.CSP_I_ABONO_TELETRABAJO) AS PAID,
 CONVERT(varchar(19), A.DT_LAST_UPDATE, 120) AS CALCULATED
${accumulatorJoin}`,

  /** CSP_PAGA_MES_ANTERIOR: allocation of the previous month and person, every payment. */
  previous: `SELECT SCO_ID_HR AS EMPLOYEE,
 CONVERT(varchar(100), ISNULL(SSP_DIAS_MATERN, 0) + ISNULL(SSP_DIAS_PATERN, 0)
  + ISNULL(SSP_DIAS_ENF_C_EMP, 0) + ISNULL(SSP_DIAS_ENF_C_IND, 0) + ISNULL(SSP_DIAS_ENF_60, 0)
  + ISNULL(SSP_DIAS_ENF_75, 0) + ISNULL(SSP_DIAS_ACCID, 0)) AS LEAVE_DAYS
FROM M4SCO_AC_HR_PERIOD WHERE ID_ORGANIZATION = @organization
 AND SCO_DT_ALLOC = @previousDate`,

  defaults: `SELECT ID_ITEM AS COMPONENT, DEFAULT_VALUE AS VALUE,
 CONVERT(varchar(19), DT_LAST_UPDATE, 120) AS UPDATED
FROM M4RCH_ITEMS WHERE ID_TI = 'CSP_HRPERIOD_CALC' AND ID_ITEM IN ${components}
 AND ID_DMD = 'DMD1' AND ID_DMD_COMPONENT = ID_ITEM`,

  values: `SELECT 'individual' AS LEVEL, STD_ID_HR AS KEY1,
 CONVERT(varchar(30), STD_OR_HR_PERIOD) AS KEY2,
 ID_DMD_COMPONENT AS COMPONENT, SCO_VALUE AS VALUE, ID_PRIORITY AS PRIORITY,
 CONVERT(varchar(10), DT_START, 23) AS DATE_FROM, CONVERT(varchar(10), DT_END, 23) AS DATE_TO,
 ${written} AS UPDATED
FROM M4SCO_PERIO_VALUES WHERE ID_ORGANIZATION = @organization AND ${candidateValues}
UNION ALL
SELECT 'entity', STD_ID_LEG_ENT, NULL, ID_DMD_COMPONENT, SCO_VALUE, ID_PRIORITY,
 CONVERT(varchar(10), DT_START, 23), CONVERT(varchar(10), DT_END, 23), ${written}
FROM M4SCO_LE_VALUES WHERE ID_ORGANIZATION = @organization AND ${candidateValues}`,

  rules: `SELECT R.ID_RULE AS RULE_ID, CONVERT(varchar(10), R.DT_START, 23) AS DATE_FROM,
 CONVERT(varchar(10), R.DT_END, 23) AS DATE_TO, R.ID_PRIORITY AS PRIORITY,
 R.CONDITION_EXECUTE AS CONDITION, S.SOURCE_CODE AS SOURCE
FROM M4RCH_RULES R LEFT JOIN M4RCH_RULES3 S
 ON S.ID_TI = R.ID_TI AND S.ID_ITEM = R.ID_ITEM AND S.ID_RULE = R.ID_RULE
 AND S.ID_RULE_TI = R.ID_RULE_TI AND S.DT_START = R.DT_START
 AND S.DT_START_CORR = R.DT_START_CORR
WHERE R.ID_TI = 'CSP_HRPERIOD_CALC' AND R.ID_ITEM = 'CSP_I_ABONO_TELETRABAJO'
 AND R.ID_RULE = '_RULE_U_P'
 AND R.DT_START <= @lastDay AND R.DT_END >= @firstDay
 AND R.DT_START_CORR <= @correctionDate AND R.DT_END_CORR >= @correctionDate`,
};

