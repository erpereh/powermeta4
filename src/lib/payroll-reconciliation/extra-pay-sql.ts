/** Fixed, server-only identifiers from the existing receipt/dictionary contracts. */
const flagFilter =
  "ID_DMD_COMPONENT IN ('CSP_PRORRATEADA_PE1','CSP_PRORRATEADA_PE2','CSP_PRORRATEADA_PE3','CSP_PRORRATEADA_PE4','CSP_PRORRATEADA_PE5')";
const validValues = `ID_DMD = 'DMD1' AND ${flagFilter}
 AND DT_START <= @lastDay AND DT_END >= @firstDay
 AND DT_COR_START <= @correctionDate AND DT_COR_END >= @correctionDate`;

