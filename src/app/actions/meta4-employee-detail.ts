/** Sentinel end date Meta4 uses to mean "no end date / still active". */
const OPEN_ENDED_DATE = "4000-01-01T00:00:00.000Z";

/** Meta4 record-keeping noise, never shown regardless of section. */
const EXCLUDED_FIELD_KEYS = new Set(["m4autogeneratedrecordid", "m4autogeneratedtodelete"]);

const KNOWN_FIELD_LABELS: Record<string, { section: string; label: string }> = {
  nombre: { section: "identity", label: "Nombre" },
  apellido_1: { section: "identity", label: "Primer apellido" },
  apellido_2: { section: "identity", label: "Segundo apellido" },
  id_Legal: { section: "identity", label: "DNI" },
  fec_Nacimiento: { section: "identity", label: "Fecha de nacimiento" },
  num_Afiliacion_Ss: { section: "identity", label: "Nº afiliación S.S." },
  clave_Self: { section: "identity", label: "Usuario Meta4" },
  id_Empleado: { section: "identity", label: "Id. empleado" },
  correo: { section: "identity", label: "Correo principal" },
  correo2: { section: "identity", label: "Correo secundario" },
  n_Puesto: { section: "role", label: "Puesto" },
  n_Clase_Puesto: { section: "role", label: "Clase de puesto" },
  n_Unidad: { section: "role", label: "Unidad" },
  n_Area: { section: "role", label: "Área" },
  n_Direccion: { section: "role", label: "Dirección (organización)" },
  id_Organization: { section: "role", label: "Organización" },
  n_Centro_Trabajo: { section: "workplace", label: "Centro de trabajo" },
  dir_Centro_Trabajo: { section: "workplace", label: "Dirección del centro" },
  fec_Antiguedad: { section: "labor", label: "Fecha de antigüedad" },
  fec_Alta_Empleado: { section: "labor", label: "Fecha de alta" },
  std_N_Leg_Ent: { section: "labor", label: "Entidad legal" },
};

const SECTION_TITLES: Record<string, string> = {
  identity: "Datos personales",
  role: "Puesto y organización",
  workplace: "Centro de trabajo",
  labor: "Datos laborales",
  other: "Otros datos",
};

const SECTION_ORDER = ["identity", "role", "workplace", "labor", "other"];

const pickField = (fields: Record<string, string>, name: string): string => {
  const found = Object.entries(fields).find(([key]) => key.toLowerCase() === name.toLowerCase());
  return found?.[1] ?? "";
};

const buildEmployeeSections = (fields: Record<string, string>): Meta4ProfileSectionView[] => {
  const buckets = new Map<string, Meta4ProfileFieldView[]>();
  const push = (section: string, field: Meta4ProfileFieldView) => {
    const list = buckets.get(section) ?? [];
    list.push(field);
    buckets.set(section, list);
  };

  for (const [key, raw] of Object.entries(fields)) {
    if (EXCLUDED_FIELD_KEYS.has(key.toLowerCase())) continue;
    const known = KNOWN_FIELD_LABELS[key];
    push(known?.section ?? "other", {
      key,
      label: known?.label ?? humanizeKey(key),
      value: formatFieldValue(raw),
    });
  }

  return SECTION_ORDER.filter((id) => (buckets.get(id)?.length ?? 0) > 0).map((id) => ({
    id,
    title: SECTION_TITLES[id] ?? id,
    fields: buckets.get(id) ?? [],
  }));
};

const formatEmailDateRange = (startDate: string, endDate: string): string => {
  const start = formatFieldValue(startDate);
  const end = endDate.trim() === OPEN_ENDED_DATE ? "Vigente" : formatFieldValue(endDate);
  return `${start} – ${end}`;
};

const buildEmployeeEmails = (result: Meta4EmployeeDetailResult): Meta4EmployeeEmailView[] =>
  [...result.emails]
    .sort((a, b) => Number(a.order) - Number(b.order))
    .map((email) => ({
      email: email.email,
      dateRange: formatEmailDateRange(email.startDate, email.endDate),
    }));

const unavailableView = (employeeId: string, message: string): Meta4EmployeeDetailView => ({
  available: false,
  employeeId,
  displayName: null,
  message,
  sections: [],
  emails: [],
});

const genericFetchFailedMessage = "No se ha podido cargar el detalle del empleado desde Meta4.";

const resolveErrorMessage = (error: unknown): string => {
  if (isMeta4ConsultaOroError(error)) return error.message;
  if (isMeta4UsersError(error)) return error.message;
  if (isMeta4ProfileError(error)) return error.message;
  if (error instanceof SessionExpiredError) return error.message;
  if (error instanceof Meta4SoapFaultError) return "Meta4 rechazó la consulta del empleado.";
  if (error instanceof Meta4HttpError) return "Meta4 no pudo completar la consulta del empleado.";
  if (error instanceof Error && error.message.trim()) return error.message;
  return genericFetchFailedMessage;
};

export async function getMeta4EmployeeDetailViewAction(
  employeeId: string,
): Promise<Meta4EmployeeDetailView> {
  const authSession = await requireAuthContext();

  try {
    const { users } = await listMeta4Users(authSession);
    const belongsToActiveSociety = users.some((user) => user.id === employeeId);
    if (!belongsToActiveSociety) {
      throw new Meta4ConsultaOroError(
        "META4_CONSULTA_ORO_FORBIDDEN",
        "Este empleado no pertenece a la sociedad activa.",
      );
    }

    const result = await getMeta4EmployeeDetail(employeeId);
    const displayName = buildFullName(
      pickField(result.fields, "nombre"),
      pickField(result.fields, "apellido_1"),
      pickField(result.fields, "apellido_2"),
    );

    return {
      available: true,
      employeeId,
      displayName,
      message: null,
      sections: buildEmployeeSections(result.fields),
      emails: buildEmployeeEmails(result),
    };
  } catch (error) {
    return unavailableView(employeeId, resolveErrorMessage(error));
  }
}
